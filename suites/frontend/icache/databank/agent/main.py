"""Agent for ICacheDataBank.

The bank is a way-masked write,全-way read SRAM bank with a single port. The
agent drives a level, waits for the port to accept it (``ready`` is generated by
the macro's reset sequence, so waiting is required rather than counting cycles),
and then reads the array back to compare against the reference model.

Nothing here assumes a fixed reset length or response latency; every wait is
bounded and fails loudly.
"""

from __future__ import annotations

from typing import Any

from toffee import ClockCycles
from toffee import Execution
from toffee.signals import sample_signal

from suites.frontend.icache.bist import BistBank
from suites.frontend.icache.drivers.level import LevelDriver
from suites.frontend.icache.databank.bundle.ports import DataBankPorts
from suites.frontend.icache.databank.model.bank import DataBankModel
from suites.frontend.icache.databank.model.bank import DataEntry


# A should-reset SRAM macro clears one set per cycle, so the reset sequence
# takes as many cycles as the array has sets. Bounds are derived from that
# architecture fact instead of a magic constant.
RESET_MARGIN = 32
NUM_SETS = 256
NUM_WAYS = 4


class DataBankAgent:
    def __init__(self, dut: Any, *, sets: int = NUM_SETS, ways: int = NUM_WAYS) -> None:
        self.dut = dut
        self.ports = DataBankPorts.bind(dut)
        self.model = DataBankModel(sets, ways)
        self.read_driver = LevelDriver(self.ports.read)
        self.write_driver = LevelDriver(self.ports.write)
        self.bist = BistBank(dut)
        self._execution: Execution | None = None

    # -- lifecycle ----------------------------------------------------------
    async def start(self, execution: Execution) -> "DataBankAgent":
        self._execution = execution
        self.idle_inputs()
        await self.reset()
        return self

    async def aclose(self) -> None:
        for driver in (self.read_driver, self.write_driver):
            driver.close()
        self._execution = None

    def idle_inputs(self) -> None:
        self.read_driver.set({"valid": 0, "setIdx": (0,) * self.model.ways, "waymask": 0})
        self.write_driver.set({"valid": 0, "setIdx": 0, "waymask": 0, "data": 0, "code": 0})
        self.bist.idle()

    async def _edge(self) -> None:
        await ClockCycles(self.dut.clock, 1)

    async def reset(self, cycles: int = 4) -> None:
        self.idle_inputs()
        self.dut.reset.Set(1)
        for _ in range(cycles):
            await self._edge()
        self.dut.reset.Set(0)
        for _ in range(2):
            await self._edge()
        self.model = DataBankModel(self.model.sets, self.model.ways)

    # -- observation --------------------------------------------------------
    @staticmethod
    def _bit(signal: Any) -> int:
        return int(sample_signal(signal).as_int()) & 1

    def read_ready(self) -> int:
        return self._bit(self.ports.read_ready.bits["ready"])

    def write_ready(self) -> int:
        return self._bit(self.ports.write_ready.bits["ready"])

    def read_entries(self) -> tuple[DataEntry, ...]:
        return tuple(
            DataEntry(
                data=int(sample_signal(entry["data"]).as_int()),
                code=int(sample_signal(entry["code"]).as_int()),
            )
            for entry in self.ports.response
        )

    def settle_cycles(self) -> int:
        return self.model.sets + RESET_MARGIN

    async def wait_for(self, predicate, *, what: str, cycles: int | None = None) -> None:
        cycles = self.settle_cycles() if cycles is None else cycles
        for _ in range(cycles):
            if predicate():
                return
            await self._edge()
        if not predicate():
            raise TimeoutError(f"{what} did not happen within {cycles} edges")

    # -- operations ---------------------------------------------------------
    async def write(
        self,
        set_index: int,
        waymask: int,
        *,
        data: int,
        code: int = 0,
    ) -> None:
        """Write one entry into every way selected by ``waymask``."""
        self.write_driver.set({
            "valid": 1, "setIdx": set_index, "waymask": waymask,
            "data": data, "code": code,
        })
        # The macro asserts ready only after its reset sequence completes.
        await self.wait_for(lambda: self.write_ready() == 1, what="write ready")
        await self._edge()   # the write is accepted on this edge
        self.write_driver.set({
            "valid": 0, "setIdx": 0, "waymask": 0, "data": 0, "code": 0,
        })
        self.model.write(set_index, waymask, DataEntry(data, code))
        await self._edge()

    async def read(self, set_index: int) -> tuple[DataEntry, ...]:
        """Read every way of ``set_index`` and return what the bank presents."""
        entry = {"valid": 1, "setIdx": (set_index,) * self.model.ways, "waymask": 0b1111}
        self.read_driver.set(entry)
        await self.wait_for(lambda: self.read_ready() == 1, what="read ready")
        await self._edge()
        self.read_driver.set({"valid": 0, "setIdx": (0,) * self.model.ways, "waymask": 0})
        # The response follows the accepting edge by the macro's read latency.
        settled = (0, 0, 0, 0)
        for _ in range(self.settle_cycles()):
            await self._edge()
            values = self.read_entries()
            if tuple(item.data for item in values) == tuple(
                    item.data for item in self.model.read(set_index)):
                settled = values
                break
            settled = values
        return settled

    async def bist_command(self, *, array: int = 0, all_arrays: int = 0,
                           readen: int = 1, writeen: int = 0, be: int = 0,
                           addr: int = 0, addr_rd: int = 0,
                           indata: int = 0, hold: int = 2) -> tuple[int, int]:
        return await self.bist.command(
            self._edge, "", array=array, all_arrays=all_arrays, readen=readen,
            writeen=writeen, be=be, addr=addr, addr_rd=addr_rd, indata=indata,
            hold=hold)

    async def check_read(self, set_index: int) -> tuple[DataEntry, ...]:
        expected = self.model.read(set_index)
        actual = await self.read(set_index)
        if actual != expected:
            raise AssertionError(
                f"set {set_index}: bank returned {actual} != model {expected}")
        return actual
