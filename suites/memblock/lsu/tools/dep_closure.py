#!/usr/bin/env python3
"""Compute dependency closure of generated SystemVerilog modules.

Generated by `--split-verilog`, so one module per file (plus parameter
variants). Starting from a top module, walk instantiations and emit the
minimal file set needed to elaborate it. This keeps each DUT's picker
build small enough to iterate, instead of feeding all ~2000 files.
"""

from __future__ import annotations
import ucv.runtime as ucv_paths

import argparse
import json
import re
import sys
from pathlib import Path
from collections import defaultdict, deque

MODULE_RE = re.compile(r"^module\s+([A-Za-z_][A-Za-z0-9_$]*)", re.MULTILINE)

# Instantiation forms emitted by firtool: `Name inst (`, `Name #(...) inst (`.
# Exclude keywords and declarations.
KEYWORDS = {
    "module", "endmodule", "input", "output", "inout", "wire", "reg", "logic",
    "assign", "always", "always_ff", "always_comb", "always_latch", "initial",
    "if", "else", "case", "casez", "casex", "endcase", "for", "while", "return",
    "begin", "end", "function", "endfunction", "automatic", "task", "endtask",
    "generate", "endgenerate", "genvar", "parameter", "localparam", "typedef",
    "struct", "enum", "packed", "signed", "unsigned", "unique", "priority",
    "default", "break", "continue", "wait", "disable", "forever", "repeat",
}

INST_RE = re.compile(
    r"^[ \t]*([A-Za-z_][A-Za-z0-9_$]*)[ \t]+(?:#\s*\([^;]*?\)\s*)?([A-Za-z_][A-Za-z0-9_$]*)[ \t]*\(",
    re.MULTILINE,
)


def scan(path: Path) -> tuple[list[str], set[str]]:
    text = path.read_text(errors="replace")
    defined = MODULE_RE.findall(text)
    # Strip comments to avoid matching prose.
    body = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    used = set()
    for name, _inst in INST_RE.findall(body):
        if name not in KEYWORDS:
            used.add(name)
    return defined, used


def _cache_path(rtl: Path) -> Path:
    return Path(str(ucv_paths.scratch_root())) / f"lsu-dep-closure-{rtl.name}-{abs(hash(str(rtl.resolve()))) % 10**8}.json"


def load_index(rtl: Path) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """Scan once per source-file fingerprint; reuse on later invocations."""
    files = sorted(rtl.glob("*.sv")) + sorted(rtl.glob("*.v"))
    fingerprint = {
        f.name: [f.stat().st_size, f.stat().st_mtime_ns] for f in files
    }
    cache = _cache_path(rtl)
    if cache.is_file():
        try:
            cached = json.loads(cache.read_text())
            if cached.get("fingerprint") == fingerprint:
                return cached["defined_by"], cached["used_by"]
        except (json.JSONDecodeError, KeyError):
            pass

    defined_by: dict[str, list[str]] = defaultdict(list)
    used_by: dict[str, list[str]] = {}
    for f in files:
        defined, used = scan(f)
        used_by[f.name] = sorted(used)
        for d in defined:
            defined_by[d].append(f.name)
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_text(json.dumps({
        "fingerprint": fingerprint,
        "defined_by": defined_by,
        "used_by": used_by,
    }))
    return defined_by, used_by


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rtl", required=True, type=Path)
    ap.add_argument("--top", required=True, nargs="+")
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--report", action="store_true")
    args = ap.parse_args()

    files = sorted(args.rtl.glob("*.sv")) + sorted(args.rtl.glob("*.v"))
    defined_by, used_by = load_index(args.rtl)

    needed: set[Path] = set()
    missing: set[str] = set()
    queue = deque(args.top)
    seen: set[str] = set()
    while queue:
        mod = queue.popleft()
        if mod in seen:
            continue
        seen.add(mod)
        providers = defined_by.get(mod)
        if not providers:
            missing.add(mod)
            continue
        for name in providers:
            p = args.rtl / name
            if p in needed:
                continue
            needed.add(p)
            for child in used_by[name]:
                if child not in seen:
                    queue.append(child)

    # Verilator also needs vendored helper modules that are not instantiated
    # by name (macros expanded to cells).
    for extra in ("ClockGate.sv",):
        p = args.rtl / extra
        if p.is_file():
            needed.add(p)

    ordered = sorted(needed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("".join(f"{p.name}\n" for p in ordered))

    if args.report:
        print(f"top={','.join(args.top)}", file=sys.stderr)
        print(f"files={len(ordered)}", file=sys.stderr)
        for p in ordered:
            print(f"  {p.name}", file=sys.stderr)
        if missing:
            print(f"UNRESOLVED (external/undef): {sorted(missing)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
