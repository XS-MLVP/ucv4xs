"""Actual full-entry bus/bypass and NC RAR, not fake NC-tagged cache reads."""
import pytest

from lsqverify.rar.types import Query as RarQuery
from lsqverify.vlq.types import QueuePtr, Redirect, RobPtr
from .uncache_owners import UncacheOwners


@pytest.mark.parametrize("kind", ("nc", "mmio_memory", "io"))
@pytest.mark.parametrize("lane", range(3))
async def test_all_16_real_uncache_entries_two_generations_original_data_faults_and_bypass(lsq, kind, lane):
    trace = UncacheOwners(lsq, kind=kind)
    for generation in range(2):
        start = 16 * generation
        loads = [trace.make_load(pos) for pos in range(start, start + 16)]
        await trace.dispatch(loads, with_store=generation == 0)
        await trace.enqueue(list(range(start, start + 16)))
        attempts = []
        if kind == "nc":
            for _ in range(16):
                attempt = await trace.transfer(error=bool(len(trace.attempts) & 1), nderr=bool(len(trace.attempts) & 2))
                attempts.append(attempt)
            await trace.consume_visible(range(start, start + 16), lane)
        else:
            for pos in range(start, start + 16):
                trace.set_head(trace.loads[pos]["load"].execution.uop.rob)
                fault = generation == 1 and pos == start + 15
                attempts.append(await trace.transfer(wanted=pos, error=fault, nderr=fault))
                await trace.consume(pos, lane)
                # No movement beyond a faulted final head: LSQ completion is
                # NOT a claimed Backend trap/ROB retirement implementation.
        assert {attempt["mid"] for attempt in attempts} == set(range(16))
        await trace.idle(8)
        assert all(state["completed"] for state in trace.loads)
    await trace.finish()
    assert len(trace.attempts) == len(trace.loads) == 32
    lsq.prove("LSQ-BUS.load_only", "LSQ-BUS.ack_route", "LSQ-BUS.resp_route", "LSQ-EXCEPTION.load_clean", "LSQ-EXCEPTION.load_fault")


@pytest.mark.parametrize("same_line", (False, True), ids=("different-line-control", "real-nc-retry-and-recovery"))
@pytest.mark.parametrize("lane", range(3))
async def test_real_nc_returned_data_sets_rar_and_retries_older_read_with_actual_new_response(lsq, lane, same_line):
    trace = UncacheOwners(lsq)
    old = trace.make_load(0, rob=RobPtr.encode(11))
    young = trace.make_load(1, rob=RobPtr.encode(13), same_pa=old.paddr if same_line else None)
    await trace.dispatch([old, young], with_store=True)
    trace.set_head(old.execution.uop.rob)  # old Store is retired, still NOT consumed.
    await trace.enqueue([0])
    await trace.transfer(wanted=0, value=0x1111222233334444)
    # Same-block external requests do not overlap: first resp already fired.
    await trace.enqueue([1])
    await trace.transfer(wanted=1, value=0x1111222233334444)
    await trace.grant(1)
    await trace.bypass(1, lane)
    queries = [RarQuery()] * 3
    queries[lane] = RarQuery(True, young.execution.uop.rob, young.execution.uop.lq, young.paddr, True, True)
    await trace.cycle(rar_queries=tuple(queries))
    assert lsq.pre_observed[f"io_ldu_rarNukeQuery_{lane}_req_ready"]
    await trace.feedback(1)
    await trace.grant(0)
    await trace.bypass(0, lane)
    queries[lane] = RarQuery(True, old.execution.uop.rob, old.execution.uop.lq, old.paddr, True, True)
    await trace.cycle(rar_queries=tuple(queries))
    lsq.expect({f"io_ldu_rarNukeQuery_{lane}_resp_valid": 1, f"io_ldu_rarNukeQuery_{lane}_resp_bits_nuke": int(same_line)},
               "real NC data, not a fake cached NC tag, marks the younger reader released")
    lsq.reach("LSQ-RAR.nc")
    if same_line:
        # NewLoadUnit1111-1115 prioritizes C_UNCACHE for an NC replay nuke.
        # A separate real public branch recovery cancels the young suffix;
        # it is NOT claimed to be an automatic redirect generated by RAR.
        await trace.feedback(0, retry_nc=True, redirect=Redirect(True, RobPtr.encode(12), False))
        assert await trace.recover() == QueuePtr.encode(1)
        await trace.transfer(wanted=0, value=0x5555666677778888)
        await trace.grant(0)
        await trace.bypass(0, lane)
        await trace.cycle(rar_queries=tuple(queries))
        lsq.expect({f"io_ldu_rarNukeQuery_{lane}_resp_bits_nuke": 0}, "cancelled young NC record cannot poison the actual fresh read")
        await trace.feedback(0)
        await trace.idle(6)
        new = trace.make_load(1, rob=RobPtr.encode(14), same_pa=young.paddr)
        await trace.dispatch([new])
        await trace.enqueue([2])  # new UID reuses original physical LQ1.
        await trace.transfer(wanted=1, value=0x9999AAAABBBBCCCC)
        await trace.consume(2, lane)
    else:
        await trace.feedback(0)
    await trace.finish()
    lsq.prove("LSQ-RAR.nc")
    if same_line:
        lsq.prove("LSQ-RECOVER.partial", "LSQ-RECOVER.concurrent", "LSQ-RECOVER.retired_store", "LSQ-RECOVER.reuse")
