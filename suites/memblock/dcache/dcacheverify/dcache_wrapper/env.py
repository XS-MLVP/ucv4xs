"""Environment for the MemBlock-level `DCacheWrapper` DUT.

`DCacheWrapper` is a *structural* wrapper around the very same `DCache` RTL used
by the DCache top-level UT: it instantiates one `DCache` and renames two port
groups (866 identity connections + 14 cache-control + 39 speculative-fabric
renames).  There is no additional datapath, no uncache arbitration and no third
L2 channel inside this module — the real `Uncache` sits next to it in
`MemBlock.sv`.

Therefore the honest way to verify the wrapper is:

1. prove the port mapping is complete and 1:1 (from the generated RTL, not by
   assumption), and
2. run the same behavioural checks through the *wrapper* ports, so that the
   rename layer plus the wrapped DCache really produces the expected results.

`WrapperDutView` provides exactly that: an attribute view that maps the wrapper
port names onto the DCache port names used by `DcacheEnv`.  The DUT under test is
the real `DCacheWrapper` netlist; only the Python attribute names are translated.
"""
from __future__ import annotations

import json
from pathlib import Path

from ..dcache.env import DcacheEnv

ROOT = Path(__file__).resolve().parents[2]


def load_portmap() -> dict:
    path = ROOT / "manifest/dcache-wrapper-portmap.json"
    return json.loads(path.read_text())


class WrapperDutView:
    """Map wrapper port names to the inner DCache port names.

    The mapping comes from `manifest/dcache-wrapper-portmap.json`, generated by
    `tools/wrapper_portmap.py` from the actual `DCacheWrapper.sv` instantiation.
    Anything not listed is an identity connection.
    """

    def __init__(self, dut) -> None:
        self._dut = dut
        portmap = load_portmap()
        # wrapper -> inner, so `getattr(view, <DCache port name>)` resolves the
        # corresponding wrapper pin (identity for 766 ports).
        self._rename = dict(portmap["wrapper_to_inner"])
        self.mapping = portmap

    def __getattr__(self, name: str):
        inner = self._rename.get(name, name)
        return getattr(self._dut, inner)


class DcacheWrapperEnv(DcacheEnv):
    """DCache environment driven through the DCacheWrapper ports."""

    def __init__(self, dut, coverage=None) -> None:
        self.raw_dut = dut
        self.view = WrapperDutView(dut)
        self.ctrl = {
            "a_ready": dut.auto_uncache_in_a_ready,
            "a_valid": dut.auto_uncache_in_a_valid,
            "a_opcode": dut.auto_uncache_in_a_bits_opcode,
            "a_size": dut.auto_uncache_in_a_bits_size,
            "a_source": dut.auto_uncache_in_a_bits_source,
            "a_address": dut.auto_uncache_in_a_bits_address,
            "a_mask": dut.auto_uncache_in_a_bits_mask,
            "a_data": dut.auto_uncache_in_a_bits_data,
            "d_ready": dut.auto_uncache_in_d_ready,
            "d_valid": dut.auto_uncache_in_d_valid,
            "d_opcode": dut.auto_uncache_in_d_bits_opcode,
            "d_size": dut.auto_uncache_in_d_bits_size,
            "d_source": dut.auto_uncache_in_d_bits_source,
            "d_data": dut.auto_uncache_in_d_bits_data,
        }
        super().__init__(self.view, coverage)

    # ------------------------------------------------------- control register
    def ctrl_write(self, index: int, data: int, mask: int = 0xFF, *,
                   source: int = 7) -> dict:
        self.ctrl["a_valid"].Set(1)
        self.ctrl["a_opcode"].Set(0)      # PutFullData
        self.ctrl["a_size"].Set(3)
        self.ctrl["a_source"].Set(source)
        self.ctrl["a_address"].Set(index * 8)
        self.ctrl["a_mask"].Set(mask)
        self.ctrl["a_data"].Set(data)
        self.ctrl["d_ready"].Set(1)
        accepted = False
        for _ in range(8):
            self.refresh()
            if self._val(self.ctrl["a_ready"]):
                accepted = True
                break
            self.dut.Step(1)
        if not accepted:
            self.ctrl["a_valid"].Set(0)
            raise AssertionError(f"ctrl write index {index}: A channel stayed busy")
        self.dut.Step(1)
        self.ctrl["a_valid"].Set(0)
        response = None
        for _ in range(8):
            self.refresh()
            if self._val(self.ctrl["d_valid"]):
                response = {
                    "opcode": self._val(self.ctrl["d_opcode"]),
                    "size": self._val(self.ctrl["d_size"]),
                    "source": self._val(self.ctrl["d_source"]),
                    "data": self._val(self.ctrl["d_data"]),
                }
                self.dut.Step(1)
                return response
            self.dut.Step(1)
        raise AssertionError(f"ctrl write index {index}: no D response")

    def ctrl_read(self, index: int, *, source: int = 7) -> dict:
        self.ctrl["a_valid"].Set(1)
        self.ctrl["a_opcode"].Set(4)      # Get
        self.ctrl["a_size"].Set(3)
        self.ctrl["a_source"].Set(source)
        self.ctrl["a_address"].Set(index * 8)
        self.ctrl["a_mask"].Set(0)
        self.ctrl["a_data"].Set(0)
        self.ctrl["d_ready"].Set(1)
        for _ in range(8):
            self.refresh()
            if self._val(self.ctrl["a_ready"]):
                break
            self.dut.Step(1)
        else:
            self.ctrl["a_valid"].Set(0)
            raise AssertionError(f"ctrl read index {index}: A channel stayed busy")
        self.dut.Step(1)
        self.ctrl["a_valid"].Set(0)
        for _ in range(8):
            self.refresh()
            if self._val(self.ctrl["d_valid"]):
                response = {
                    "opcode": self._val(self.ctrl["d_opcode"]),
                    "size": self._val(self.ctrl["d_size"]),
                    "source": self._val(self.ctrl["d_source"]),
                    "data": self._val(self.ctrl["d_data"]),
                }
                self.dut.Step(1)
                return response
            self.dut.Step(1)
        raise AssertionError(f"ctrl read index {index}: no D response")
